export class MapParser {

    static parse(chunk) {

        /*
         * Color / Object 레이어 파싱
         */

        const colorRows = (chunk.color ?? "")
            .trim()
            .split("\n")
            .map(row => row.trim())
            .filter(row => row.length > 0);

        const objectRows = (chunk.object ?? "")
            .trim()
            .split("\n")
            .map(row => row.trim())
            .filter(row => row.length > 0);

        if (colorRows.length === 0 || objectRows.length === 0) {

            throw new Error(
                "Map data must contain at least one row."
            );
        }


        const explicitWidth = Number.isInteger(chunk.width)
            ? chunk.width
            : null;

        const explicitHeight = Number.isInteger(chunk.height)
            ? chunk.height
            : null;

        const height = explicitHeight ?? colorRows.length;
        const width = explicitWidth ?? Math.max(
            ...colorRows.map(row => row.length),
            ...objectRows.map(row => row.length),
            0
        );


        if (objectRows.length !== height) {

            throw new Error(
                `Object map height must match color map height. Got ${objectRows.length} and ${height}.`
            );
        }


        const normalizedColorRows = Array.from(
            { length: height },
            (_, y) =>
                (colorRows[y] ?? "").padEnd(width, ".").slice(0, width)
        );

        const normalizedObjectRows = Array.from(
            { length: height },
            (_, y) =>
                (objectRows[y] ?? "").padEnd(width, ".").slice(0, width)
        );


        /*
         * 최종 파싱 결과
         */

        const result = {

            width,
            height,
            map: [],

            objects: {
                player: [],
                goal: []
            }
        };


        /*
         * 타일 파싱
         */

        for (let y = 0; y < height; y++) {

            const row = [];


            for (let x = 0; x < width; x++) {

                const color = normalizedColorRows[y][x];
                const object = normalizedObjectRows[y][x];


                /*
                 * 색상 → RGB 데이터
                 */

                let tile = {

                    R: false,
                    G: false,
                    B: false
                };


                switch (color) {

                    case ".":
                        break;

                    case "R":
                        tile.R = true;
                        break;

                    case "G":
                        tile.G = true;
                        break;

                    case "B":
                        tile.B = true;
                        break;

                    case "Y":
                        tile.R = true;
                        tile.G = true;
                        break;

                    case "M":
                        tile.R = true;
                        tile.B = true;
                        break;

                    case "C":
                        tile.G = true;
                        tile.B = true;
                        break;

                    case "W":
                        tile.R = true;
                        tile.G = true;
                        tile.B = true;
                        break;

                    default:

                        throw new Error(
                            `Unknown color "${color}" at (${x}, ${y})`
                        );
                }


                /*
                 * 오브젝트 처리
                 */

                switch (object) {

                    // Empty
                    case ".":
                        break;


                    // Block
                    case "#":

                        tile.type = "block";

                        break;


                    // Player
                    case "@":

                        result.objects.player.push({
                            x: x,
                            y: y
                        });

                        break;


                    // Goal
                    case "$":

                        result.objects.goal.push({
                            x: x,
                            y: y
                        });

                        break;


                    // Spike
                    case "^":

                        tile.type = "spike";

                        break;


                    default:

                        throw new Error(
                            `Unknown object "${object}" at (${x}, ${y})`
                        );
                }


                row.push(tile);
            }


            result.map.push(row);
        }


        return result;
    }
}


export const stageArray = stage.map(
    chunk => MapParser.parse(chunk)
);